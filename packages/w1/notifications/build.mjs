import {readFile,mkdir,writeFile} from 'node:fs/promises';
const base=new URL('./',import.meta.url);
const state=(await readFile(new URL('src/state.js',base),'utf8')).replaceAll('export ','');
const settings=await readFile(new URL('src/settings.js',base),'utf8');
const client=await readFile(new URL('src/client.js',base),'utf8');
await mkdir(new URL('lib/',base),{recursive:true});
await writeFile(new URL('lib/client.js',base),'// Generated by build.mjs.\nwindow.__ModuleLoader__.load({id:"@w1h/notifications",factory:(require)=>{\n'+state+'\n'+settings+'\n'+client+'\nreturn {apply,inject};\n}});\n');
console.log('Built W1 notifications');
